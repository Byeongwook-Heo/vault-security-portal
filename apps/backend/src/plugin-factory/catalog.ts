export function generateVaultPluginScaffold(request: VaultPluginGenerateRequest): VaultPluginGenerateResult {
  const template = findPluginTemplate(request.templateId);
  const pluginName = normalizePluginName(request.pluginName);
  const mountPath = normalizeMountPath(request.mountPath);
  const requirements = normalizeRequirements(request.requirements, template, mountPath);
  const version = normalizeVersion(request.version);
  const command = normalizeCommand(request.command);
  const description =
    request.description?.trim() || `${template.displayName} generated by the Security Portal Vault Plugin Factory`;
  const moduleName = `example.com/${pluginName}`;
  const generatedAt = new Date().toISOString();
  const files = buildFiles({
    template,
    pluginName,
    mountPath,
    version,
    command,
    description,
    moduleName,
    requirements
  });
  const scaffoldSha256 = hashFiles(files);
  const enableCommand =
    template.pluginType === "auth"
      ? `vault auth enable -path=${mountPath} ${pluginName}`
      : `vault secrets enable -path=${mountPath} ${pluginName}`;
  const commands = [
    "factory build start --isolated",
    "gofmt -w ./...",
    "go mod tidy",
    "go test ./...",
    "mkdir -p dist",
    `GOOS=linux GOARCH=arm64 CGO_ENABLED=0 go build -o dist/${command} ./cmd/${pluginName}`,
    `PLUGIN_SHA=$(sha256sum dist/${command} | awk '{print $1;}')`,
    `vault plugin register -command=${command} -sha256=$PLUGIN_SHA -version=${version} ${template.pluginType} ${pluginName}`,
    enableCommand
  ];
  const applyPlan = [
    "Verify Vault health, plugin_directory, api_addr, and the least-privilege plugin AppRole.",
    "Compile and test the confirmed specification in the isolated Factory CodeBuild runner.",
    `Copy dist/${command} to the Vault plugin_directory on every Vault node.`,
    `Register ${pluginName} in the ${template.pluginType} plugin catalog with the binary SHA256.`,
    `Enable ${pluginName} at ${mountPath}/ using the registered version ${version}.`,
    "Run a mount/read smoke test and capture the plugin version and running SHA256."
  ];
  const warnings = [
    "The scaffold SHA is for generated source review only; real Vault registration requires the compiled binary SHA256.",
    "Apply is safe in mock mode. Real mode requires the binary to already exist under Vault's plugin_directory.",
    template.pluginType === "auth"
      ? "Auth plugins require sudo capability on sys/auth and should be promoted through approval."
      : "Secrets and database plugins require create/update capability on sys/mounts and catalog registration."
  ];
  if (template.integrationTarget === "github-pat") {
    warnings.push(
      "GitHub does not expose a public API to create PATs; this plugin validates and rotates an operator-supplied PAT.",
      "Automated retirement revokes a fine-grained PAT's organization access only; classic PATs require manual revocation."
    );
  }

  return {
    id: crypto.randomUUID(),
    template,
    pluginName,
    mountPath,
    version,
    command,
    description,
    generatedAt,
    scaffoldSha256,
    files,
    commands,
    applyPlan,
    warnings,
    requirements,
    blueprint: buildBlueprint({ template, pluginName, mountPath, version, command, description, requirements }),
    dryRun: buildDryRunPlan({ template, pluginName, mountPath, version, command }),
    buildTest: buildBuildTestPlan({ template, pluginName, command, files }),
    rollbackPlan: buildRollbackPlan({ template, pluginName, mountPath, version }),
    securityReview: buildSecurityReview({ template, files, warnings })
  };
}

export function findPluginTemplate(templateId: string): VaultPluginTemplate {
  const template = vaultPluginTemplates.find((item) => item.id === templateId);
  if (!template) {
    throw new Error(`Unknown Vault plugin template: ${templateId}`);
  }
  return template;
}

function expansionTemplate(template: FactoryExpansionTemplate): VaultPluginTemplate {
  return baseTemplate({
    id: template.id,
    name: template.name,
    displayName: template.displayName,
    pluginType: template.pluginType,
    source: template.source,
    repository: template.repository,
    sourceUrl: template.sourceUrl ?? `https://github.com/${template.repository}`,
    description: template.description,
    target: template.target,
    buildProfile: "reference",
    aliases: template.aliases,
    catalogTier: template.catalogTier,
    catalogExpansion: true
  });
}

function validateTemplateCatalog(templates: VaultPluginTemplate[]): VaultPluginTemplate[] {
  for (const field of ["id", "name"] as const) {
    const seen = new Set<string>();
    for (const template of templates) {
      const value = template[field].toLowerCase();
      if (seen.has(value)) {
        throw new Error(`Duplicate Vault plugin template ${field}: ${template[field]}`);
      }
      seen.add(value);
    }
  }
  return templates;
}

function validateExpansionTargets(templates: FactoryExpansionTemplate[]): FactoryExpansionTemplate[] {
  const reservedTargets = new Set<string>(factoryExpansionReservedTargets);
  for (const template of templates) {
    if (reservedTargets.has(template.target)) {
      throw new Error(`Reserved Vault or portal integration target in catalog expansion: ${template.target}`);
    }
  }
  return templates;
}

