function baseTemplate({
  id,
  name,
  displayName,
  pluginType,
  source,
  repository,
  sourceUrl,
  description,
  target,
  buildProfile,
  popularity,
  aliases = [],
  catalogTier,
  catalogExpansion = false
}: {
  id: string;
  name: string;
  displayName?: string;
  pluginType: VaultPluginTemplate["pluginType"];
  source: VaultPluginTemplate["source"];
  repository: string;
  sourceUrl: string;
  description: string;
  target: string;
  buildProfile: VaultPluginTemplate["buildProfile"];
  popularity?: VaultPluginTemplate["popularity"];
  aliases?: string[];
  catalogTier?: FactoryCatalogTier;
  catalogExpansion?: boolean;
}): VaultPluginTemplate {
  const typePrefix = pluginType === "secret" ? "secrets" : pluginType;
  return {
    id,
    name,
    displayName: displayName ?? name,
    pluginType,
    source,
    repository,
    sourceUrl,
    description,
    defaultMountPath: `${target}`,
    defaultCommand: name,
    defaultVersion: "v0.1.0",
    integrationTarget: target,
    buildProfile,
    popularity,
    tags: [
      pluginType,
      source,
      target,
      typePrefix,
      ...aliases,
      ...(catalogTier ? [catalogTier] : []),
      ...(catalogExpansion ? ["catalog expansion"] : []),
      ...(popularity?.rank ? ["community top 5"] : []),
      ...(source === "learning" ? ["tutorial"] : [])
    ],
    guardrails: guardrailsFor(pluginType, target),
    marketplace: marketplaceFor({ pluginType, source, target, popularity, catalogTier })
  };
}

function marketplaceFor({
  pluginType,
  source,
  target,
  popularity,
  catalogTier
}: {
  pluginType: VaultPluginTemplate["pluginType"];
  source: VaultPluginTemplate["source"];
  target: string;
  popularity?: VaultPluginTemplate["popularity"];
  catalogTier?: FactoryCatalogTier;
}): VaultPluginTemplate["marketplace"] {
  const maturity =
    catalogTier === "conditional"
      ? "conditional"
      : catalogTier === "lab"
        ? "lab-only"
        : source === "official"
      ? "production-ready"
      : source === "learning"
        ? "learning"
        : catalogTier === "priority" || popularity?.rank
          ? "reference"
          : "experimental";
  const riskLevel =
    catalogTier === "lab" ? "high" : pluginType === "auth" || source === "community" || source === "partner" ? "medium" : "low";
  return {
    maturity,
    riskLevel,
    recommendedUse:
      catalogTier === "priority"
        ? `Prioritize ${target} for compatibility, revocation, and release-artifact validation before rollout.`
        : catalogTier === "conditional"
          ? `Use ${target} only after environment-specific API and Vault compatibility checks pass.`
          : catalogTier === "lab"
            ? `Keep ${target} in build and test workflows until maintenance, compatibility, and revocation checks pass.`
            : source === "learning"
        ? `Use ${target} as a tutorial or prototype starter before hardening it.`
        : source === "community" || source === "partner"
          ? `Use ${target} as a reviewed community reference and run a security review before production.`
          : `Use ${target} as the standard starting point for a controlled Vault plugin rollout.`,
    lastReviewedAt: capturedAt,
    badges: [
      source,
      pluginType,
      maturity,
      riskLevel === "low" ? "low risk" : "review required",
      ...(catalogTier ? [catalogTier] : []),
      ...(popularity?.rank ? [`top ${popularity.rank}`] : [])
    ]
  };
}

function guardrailsFor(pluginType: VaultPluginTemplate["pluginType"], target: string): string[] {
  if (target === "github-pat") {
    return [
      "Accept newly created PATs only through a write-only rotation request and never log or echo them.",
      "Restrict creds/* reads to the intended workload with a dedicated least-privilege Vault policy.",
      "Treat fine-grained PAT organization-access revocation and classic PAT manual revocation as separate controls."
    ];
  }
  if (pluginType === "auth") {
    return [
      "Require sudo-gated approval before sys/auth enable.",
      "Constrain identity alias metadata and default policies.",
      "Add lockout and token TTL tuning before production."
    ];
  }
  if (pluginType === "database") {
    return [
      "Use least-privilege admin credentials for credential rotation.",
      "Test revoke statements against ephemeral users.",
      "Set max TTL lower than the backing database password policy window."
    ];
  }
  return [
    "Keep upstream API tokens out of generated source and audit logs.",
    "Implement renew/revoke paths before production use.",
    "Set plugin-specific environment variables in the catalog, not app code."
  ];
}

